export function isHeteronym(word) {
    if (!word) return false;
    const w = word.toLowerCase().trim();
    return Boolean(HETERONYMS_DB[w]);
}

export function getHeteronymInfo(word) {
    if (!word) return null;
    const w = word.toLowerCase().trim();
    return HETERONYMS_DB[w] || null;
}

export function inferPartOfSpeech(word, sentenceContext) {
    if (!word || !sentenceContext) return 'noun';
    const w = word.toLowerCase().trim();
    const cleanSentence = sentenceContext.toLowerCase().replace(/[^a-z0-9'\s]/g, ' ');
    const tokens = cleanSentence.split(/\s+/).filter(Boolean);
    const targetIdx = tokens.findIndex(t => t === w || t.startsWith(w));
    if (targetIdx === -1) return 'noun';

    const prevToken = targetIdx > 0 ? tokens[targetIdx - 1] : '';
    const nextToken = targetIdx < tokens.length - 1 ? tokens[targetIdx + 1] : '';

    const verbIndicators = [
        'to', 'will', 'would', 'shall', 'should', 'can', 'could', 'may', 'might',
        'must', 'do', 'does', 'did', "don't", "doesn't", "didn't", 'not', 'never',
        'always', 'please', 'i', 'you', 'he', 'she', 'we', 'they', 'who', 'which'
    ];

    const nounIndicators = [
        'a', 'an', 'the', 'this', 'that', 'these', 'those',
        'my', 'your', 'his', 'her', 'its', 'our', 'their',
        'some', 'any', 'many', 'much', 'every', 'each', 'no',
        'new', 'old', 'good', 'bad', 'great', 'big', 'small', 'high', 'low',
        'audio', 'data', 'world', 'current', 'latest', 'final'
    ];

    if (verbIndicators.includes(prevToken)) return 'verb';
    if (nounIndicators.includes(prevToken)) return 'noun';

    if (['is', 'are', 'was', 'were', 'been', 'being'].includes(prevToken)) {
        if (tokens[targetIdx].endsWith('ed') || tokens[targetIdx].endsWith('ing')) return 'verb';
    }

    if (['a', 'an', 'the', 'this', 'that', 'it', 'them', 'him', 'her', 'us', 'me'].includes(nextToken)) {
        return 'verb';
    }

    return 'noun';
}

export function formatPhoneticPrompt(word, pos = 'noun') {
    const w = word.toLowerCase().trim();
    if (!isHeteronym(w)) return word;
    if (pos === 'verb') {
        return `to ${w}`;
    }
    return `a ${w}`;
}
